import java.util.*;
public class pattern2 {
    public static void main(String[] args) {
        int n=5;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){//if (i>=j) print * else space
                System.out.print("*");
            }
        System.out.println();
        }
    }
}
